#!/usr/bin/env python3
"""Publication tables (Markdown + LaTeX booktabs + CSV) and figure set for the COMPLETED studies only: S7 (+ audit),
S8-E1, S8-E2. Every number is read from the frozen FINAL analysis outputs; nothing is recomputed here except
formatting. E3/E5 are excluded (incomplete). Output: results/publication/{tables.md, tables.tex, csv/, figures/}."""
import json
import os
import shutil

import pandas as pd

REPO = os.path.abspath(os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", ".."))
OUT = os.path.dirname(os.path.abspath(__file__))
S7A, AUD = os.path.join(REPO, "results/s7/analysis"), os.path.join(REPO, "results/s7/audit")
E1A, E2A = os.path.join(REPO, "results/s8/e1/analysis"), os.path.join(REPO, "results/s8/e2/analysis")
ARM = {"b4ts": "B4-TS", "b4tpc": "B4-TPC", "b5": "B5", "b4sats": "B4sa-TS", "b4satpc": "B4sa-TPC", "b5sa": "B5sa"}
HOLD = {"D0": "0", "D1": "0.131", "D1d1": "50.131", "D1d2": "125.131", "D1d3": "250.131"}
OUTC = {"rel_goodput": "G", "viol": "V", "G": "G", "V": "V", "min_user_frac": "min-user", "viol_edge": "edge V", "etx": "E_tx (W·s)"}
md, tex = [], []


def ci(m, lo, hi, nd=4):
    return f"{m:+.{nd}f} [{lo:+.{nd}f}, {hi:+.{nd}f}]"


def mdtable(df):
    h = "| " + " | ".join(map(str, df.columns)) + " |\n|" + "---|" * len(df.columns) + "\n"
    return h + "\n".join("| " + " | ".join(map(str, r)) + " |" for r in df.astype(str).values)


def emit(key, title, note, df):
    df.to_csv(os.path.join(OUT, "csv", f"{key}.csv"), index=False)
    md.append(f"## {key}. {title}\n\n{note}\n\n" + mdtable(df) + "\n")
    cols = "l" * len(df.columns)
    esc = lambda s: str(s).replace("%", r"\%").replace("&", r"\&").replace("_", r"\_").replace("±", r"$\pm$").replace("−", "$-$") \
        .replace("Δ", r"$\Delta$").replace("δ", r"$\delta$").replace("·", r"$\cdot$").replace("θ", r"$\theta$").replace("≥", r"$\ge$")
    tex.append(f"% {key}\n\\begin{{table}}[t]\\centering\\caption{{{esc(title)}}}\\label{{tab:{key.lower()}}}\\footnotesize\n"
               f"\\begin{{tabular}}{{{cols}}}\\toprule\n" + " & ".join(esc(c) for c in df.columns) + r" \\\midrule" + "\n"
               + "\n".join(" & ".join(esc(v) for v in r) + r" \\" for r in df.astype(str).values)
               + "\n\\bottomrule\\end{tabular}\n" + f"\\par\\smallskip\\parbox{{\\linewidth}}{{\\scriptsize {esc(note)}}}\\end{{table}}\n")


def main():
    os.makedirs(os.path.join(OUT, "csv"), exist_ok=True)
    os.makedirs(os.path.join(OUT, "figures"), exist_ok=True)
    md.append("# Publication tables: completed studies (S7, S8-E1, S8-E2)\n\nGenerated by `results/publication/make_publication.py` from the FINAL analysis outputs. "
              "E3 and E5 are not included (incomplete at generation time). Conventions: Δ = arm − reference; G = relative goodput "
              "(higher is better); V = QoS-violation fraction (higher is worse); δ = 0.01; 95 % CIs.\n")
    # T1 overview
    p7, a7 = json.load(open(os.path.join(S7A, "provenance.json"))), json.load(open(os.path.join(AUD, "audit_numbers.json")))
    p1, p2 = json.load(open(os.path.join(E1A, "provenance.json"))), json.load(open(os.path.join(E2A, "provenance.json")))
    emit("T1", "Experiments and execution", "All runs completed; 0 failed, 0 retried in every study. Derived = output provably identical to a verified source run (identity rules re-verified per study).",
         pd.DataFrame([
             ["S7 confirmatory matrix", "1001–1013", "12 conditions × 536 cells/seed", p7["runs"] - p7["derived"], p7["derived"], "FINAL"],
             ["S8-E1 event-enriched", "2001–2220", "2 joint-activity conditions; stop at ≥ 150 events", p1["runs"] - p1["derived"], p1["derived"], "FINAL (155 events)"],
             ["S8-E2 TPC sensitivity", "3001–3026", "3 TPC variants × 6 conditions", p2["runs"] - p2["derived"], p2["derived"], "FINAL"],
             ["S8-E5 load step", "5001–5026", "4 scenarios × 8 arms", "running", "–", "INCOMPLETE"],
             ["S8-E3 random geometry", "4001–4080", "80 layouts × 6 loads", "queued", "–", "INCOMPLETE"]],
             columns=["Study", "Seeds", "Design", "Simulated", "Derived", "Status"]))
    # T2 S7 F1/F2
    C = pd.read_csv(os.path.join(S7A, "confirmatory_contrasts.csv"))
    R = pd.read_csv(os.path.join(AUD, "equivalence_robustness.csv"))
    rows = []
    for _, r in C[C.family.isin(["F1 C1-D1 total", "F2 C1-D0"])].iterrows():
        o = "G" if r.outcome == "rel_goodput" else "V"
        a = R[(R.family == r.family[:2]) & (R.contrast == r.contrast) & (R.delay == r.delay) & (R.outcome == o)]
        rows.append([r.family[:2], r.delay, ARM[r.contrast.split("-")[0]], o, ci(r["mean"], r.ci_lo, r.ci_hi),
                     f"{int(r.clusters_benefit)}/{int(r.clusters_zero)}/{int(r.clusters_harm)}", f"{r.holm_p:.3g}",
                     "no difference in 156/156" if bool(a.degenerate.iloc[0]) else r.category, f"{a.delta_star.iloc[0]:.4f}"])
    emit("T2", "S7 confirmatory families F1 (D1) and F2 (D0): coordinated arm − B3",
         "13 seeds × 12 conditions (156 clusters). BCa 95 % CI (seed blocks). Clusters = benefit/zero/harm. δ* = smallest margin at which a t-based TOST still holds (audit). 'No difference in 156/156': every cluster difference is exactly 0 (rare-event bound: share of affected clusters ≤ 1.9 %).",
         pd.DataFrame(rows, columns=["Family", "Timing", "Arm", "Outcome", "Δ [95 % CI]", "Clusters", "Holm p", "Category", "δ*"]))
    # T3 S7 F3 (250 ms) and F4
    rows = []
    for _, r in C[(C.family == "F4 C2 overhead") | ((C.family == "F3 C2 arbitration") & (C.delay == "D1d3"))].iterrows():
        o = "G" if r.outcome == "rel_goodput" else "V"
        a = R[(R.family == r.family[:2]) & (R.contrast == r.contrast) & (R.delay == r.delay) & (R.outcome == o)]
        name = "B3h − B3@D1" if r.family.startswith("F4") else ARM[r.contrast.split("-")[0]] + " − B3h"
        rows.append([r.family[:2], HOLD[r.delay], name, o, ci(r["mean"], r.ci_lo, r.ci_hi),
                     f"{int(r.clusters_benefit)}/{int(r.clusters_zero)}/{int(r.clusters_harm)}", r.category, f"{a.delta_star.iloc[0]:.4f}"])
    emit("T3", "S7 coordination hold: arbitration at 250 ms (F3) and overhead B3h − B3 (F4)",
         "Hold in ms. F4 at holds ≥ 50 ms: CIs exclude 0 (detectable QoS cost) but lie inside ±δ; δ* shows how close to the margin. F3 at holds ≤ 125 ms reproduces F1 (see csv).",
         pd.DataFrame(rows, columns=["Family", "Hold (ms)", "Contrast", "Outcome", "Δ [95 % CI]", "Clusters", "Category", "δ*"]))
    # T4 E1 primary + secondary
    P = pd.read_csv(os.path.join(E1A, "e1_primary.csv"))
    S = pd.read_csv(os.path.join(E1A, "e1_secondary_DESCRIPTIVE.csv"))
    rows = [[r.arm, OUTC[r.outcome], ci(r.est, r.t95_lo, r.t95_hi), ci(r.est, r.boot_bca_lo, r.boot_bca_hi), f"{int(r.benefit)}/{int(r.events - r.nonzero)}/{int(r.harm)}",
             f"{r.holm_p:.2g}", r.category] for _, r in P.iterrows()]
    emit("T4", "S8-E1 conditional effect among reference-flagged events: arm − B3 at D1 (confirmatory)",
         "155 events in 132 seeds (x45 1.23/0.29: 112; x55 0.92/0.29: 43). Seed-cluster-robust t (df 131); BCa = seed-block bootstrap sensitivity. Events = benefit/zero/harm. Conditions selected from S7 activity evidence (disclosed); not generalisable beyond them.",
         pd.DataFrame(rows, columns=["Arm", "Outcome", "θ̂ [95 % t CI]", "θ̂ [95 % BCa]", "Events", "Holm p", "Category"]))
    rows = [[r.arm, OUTC[r.outcome], ci(r["mean"], r.t95_lo, r.t95_hi), f"{int(r.benefit)}/{int(r.events - r.nonzero)}/{int(r.harm)}"]
            for _, r in S[S.reference == "B3"].iterrows()]
    emit("T5", "S8-E1 secondary outcomes among events (descriptive): arm − B3",
         "Min-user = weakest-user goodput fraction (higher is better); edge V = violation fraction of the three edge UEs; E_tx = RF transmit-energy proxy (W·s; lower = less energy). Not a measured base-station energy.",
         pd.DataFrame(rows, columns=["Arm", "Outcome", "Δ [95 % CI]", "Events (benefit/zero/harm)"]))
    D = pd.read_csv(os.path.join(E1A, "e1_decision_consequences_DESCRIPTIVE.csv"))
    emit("T6", "S8-E1 what coordination actually did in each event, and its consequence (descriptive)",
         "Decision read from coordinator rejection/choice logs. Mean Δ vs B3 per event type; handovers and TPC reductions are per run (arm / B3).",
         pd.DataFrame([[r.arm, r.decision, int(r.events), f"{r.dG_mean:+.4f}", f"{r.dV_mean:+.4f}", f"{r.dMinUser_mean:+.4f}",
                        f"{r.ho_completed_arm:.2f} / {r.ho_completed_B3:.2f}", f"{r.tpc_reduce_arm:.2f} / {r.tpc_reduce_B3:.2f}"] for _, r in D.iterrows()],
                      columns=["Arm", "Decision", "Events", "ΔG", "ΔV", "Δmin-user", "Handovers", "TPC reductions"]))
    F = pd.read_csv(os.path.join(E1A, "e1_flag_rates.csv"))
    emit("T7", "Interaction-event frequency: S8-E1 (fresh seeds) vs S7",
         "Event = uncoordinated B3@D1 run flagged by the state-aware (combined) detector. Clopper–Pearson 95 % CI.",
         pd.DataFrame([[f"{r.pos} {r.rate_a}/{r.rate_b}", f"{int(r.events)}/{int(r.clusters)}", f"{r.rate:.3f} [{r.cp_lo:.3f}, {r.cp_hi:.3f}]", f"{int(r.s7_events)}/{int(r.s7_clusters)}"]
                       for _, r in F.iterrows()], columns=["Condition", "E1 events", "Rate [95 % CI]", "S7"]))
    # T8 E2
    A = pd.read_csv(os.path.join(E2A, "e2A_frequency.csv"))
    B = pd.read_csv(os.path.join(E2A, "e2B_interaction_contrasts.csv"))
    VN = {"V1": "27 dBm floor", "V2": "6 dB step"}
    emit("T8", "S8-E2 TPC sensitivity, frequency (E2-A): flagged clusters vs reference 24 dBm / 3 dB",
         "156 paired clusters per variant (6 conditions × 26 seeds). Exact McNemar test, Holm over 2.",
         pd.DataFrame([[VN[r.variant], f"{int(r.flagged_V0)} → {int(r.flagged_Vk)}", f"{int(r.only_V0)} / {int(r.only_Vk)}", f"{r.p_mcnemar_exact:.2f}", f"{r.holm_p:.2f}"]
                       for _, r in A.iterrows()], columns=["Variant", "Flagged (ref → variant)", "Discordant (ref only / variant only)", "p", "Holm p"]))
    emit("T9", "S8-E2 robustness of coordination effects (E2-B): interaction contrast [arm − B3h](variant) − [arm − B3h](reference)",
         "Seed-level t (df 25), δ = 0.01, Holm over the non-degenerate hypotheses. 'No difference' = all 156 cluster values exactly 0.",
         pd.DataFrame([[VN[r.variant], r.arm, r.outcome, "—" if r.degenerate else ci(r.est, r.t95_lo, r.t95_hi), int(r.nonzero),
                        r.category if not r.degenerate else f"no difference (≤ {r.cp_upper_share_nonzero:.3f} share)"] for _, r in B.iterrows()],
                      columns=["Variant", "Arm", "Outcome", "I [95 % CI]", "Non-zero clusters", "Category"]))
    # figures
    figs = {"Fig_S7_confirmatory_effects.pdf": "results/s7/analysis/figures/fig_s7_c1_effects.pdf",
            "Fig_S7_delay_decomposition.pdf": "manuscript/final/figures/fig_delay_decomposition_ms.pdf",
            "Fig_S7_single_xapp_effects.pdf": "manuscript/final/figures/fig_family_a.pdf",
            "Fig_S7_per_condition.pdf": "manuscript/final/figures/fig_per_condition.pdf",
            "Fig_D1_timeline.pdf": "manuscript/final/figures/fig_timeline.pdf",
            "Fig_E1_conditional_effects.pdf": "results/s8/e1/analysis/fig_e1_conditional_effects.pdf",
            "Fig_E1_event_accrual.pdf": "results/s8/e1/analysis/fig_e1_event_accrual.pdf",
            "Fig_E2_interaction_contrasts.pdf": "results/s8/e2/analysis/fig_e2_interactions.pdf"}
    for k, v in figs.items():
        shutil.copyfile(os.path.join(REPO, v), os.path.join(OUT, "figures", k))
    import matplotlib
    matplotlib.use("Agg")
    import matplotlib.pyplot as plt
    fig, axes = plt.subplots(1, 2, figsize=(7.2, 2.9))
    for ax, o, ttl in zip(axes, ("G", "V"), ("Δ relative goodput", "Δ violation fraction (positive = worse)")):
        q = B[B.outcome == o].reset_index(drop=True)
        ax.axvspan(-0.01, 0.01, color="#e6e6e6", lw=0)
        ax.axvline(0, color="#888", lw=0.8)
        for i, r in q.iterrows():
            if r.degenerate:
                ax.plot(0, i, "o", color="#222", mfc="white", ms=5)
            else:
                ax.errorbar(r.est, i, xerr=[[r.est - r.t95_lo], [r.t95_hi - r.est]], fmt="o", ms=5, color="#009E73", capsize=2)
        ax.set_yticks(range(len(q)))
        ax.set_yticklabels([f"{VN[r.variant]}: {r.arm}" for _, r in q.iterrows()], fontsize=7)
        ax.set_xlim(-0.012, 0.012)
        ax.set_xticks([-0.01, -0.005, 0, 0.005, 0.01])
        ax.tick_params(labelsize=7)
        ax.set_title(ttl, fontsize=8)
    fig.suptitle("E2: change in coordination effect vs the 24 dBm / 3 dB reference (95 % t CI; grey = ±δ; open = no difference in any cluster)", fontsize=7)
    fig.tight_layout()
    fig.savefig(os.path.join(OUT, "figures", "Fig_E2_interaction_contrasts.pdf"))
    plt.close(fig)
    md.append("## Figures\n\n" + "\n".join(f"- `figures/{k}`: from `{v}`" for k, v in figs.items()) + "\n")
    open(os.path.join(OUT, "tables.md"), "w").write("\n".join(md))
    open(os.path.join(OUT, "tables.tex"), "w").write("% requires booktabs\n" + "\n".join(tex))
    print("ok")


if __name__ == "__main__":
    main()
